#!/usr/bin/env node
// Writes the one definition of a reader's forecast, generated/forecast.schema.json,
// and the ward geometry the server's share card draws, generated/geometry.json,
// from the model's published artefacts.
//
// Nothing about the council is typed here: the ward list, the roster, the
// council size and the majority are read from the artefact, and the schema
// records the sha256 of every source it was built from.
//
// Sources today are the prototype's PLACEHOLDER fixtures (interactive/fixtures/),
// because the model's export (INTEGRATION.md §3a, export_draws.py) and the
// certified roster (CLAUDE.md §4b) do not exist yet. Point --model/--geometry at
// the real artefacts when they do; nothing else changes.
//
//   node tools/make_schema.mjs            write generated/*
//   node tools/make_schema.mjs --check    regenerate in memory and exit 1 if
//                                         generated/* differs (a stale schema
//                                         would validate against the wrong roster)

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");          // worker-api/
const repo = resolve(root, "..");          // the project

function arg(name, dflt) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : dflt;
}
const MODEL = resolve(repo, arg("--model", "interactive/fixtures/placeholder-model.json"));
const GEOM = resolve(repo, arg("--geometry", "interactive/fixtures/geometry.json"));
const CHECK = process.argv.includes("--check");

const sha = buf => createHash("sha256").update(buf).digest("hex");

export function build(modelBuf, geomBuf, srcNames) {
  const model = JSON.parse(modelBuf);
  const geom = JSON.parse(geomBuf);
  const codes = model.parties.map(p => p.code);
  const wardIds = geom.wards.map(w => String(w.id));

  if (wardIds.length !== model.ward_seats)
    throw new Error(`geometry has ${wardIds.length} wards; the model artefact says ward_seats=${model.ward_seats}`);
  if (new Set(codes).size !== codes.length) throw new Error("duplicate party code in roster");
  if (new Set(wardIds).size !== wardIds.length) throw new Error("duplicate ward id in geometry");

  const code = { type: "string", enum: codes };
  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://joburg.whysoserious.city/schema/forecast.schema.json",
    title: "A reader's forecast",
    description: "Generated by worker-api/tools/make_schema.mjs. Do not edit. " +
      "Checks JSON Schema cannot express (pr_share sums to 100, mayor in coalition, " +
      "coalition members distinct) are in worker-api/src/validate.js, which reads this file.",
    type: "object",
    additionalProperties: false,
    required: ["model_ref", "ward_calls", "pr_share", "coalition"],
    properties: {
      model_ref: { type: "string", enum: [model.model_ref] },
      ward_calls: { type: "array", minItems: wardIds.length, maxItems: wardIds.length, items: code },
      pr_share: {
        type: "object", additionalProperties: false, required: codes,
        properties: Object.fromEntries(codes.map(c => [c, { type: "number", minimum: 0, maximum: 100 }])),
      },
      coalition: { type: "array", minItems: 1, uniqueItems: true, items: code },
      mayor: { oneOf: [{ type: "null" }, code] },
      display_name: { oneOf: [{ type: "null" }, { type: "string", minLength: 1, maxLength: 40 }] },
    },
    "x-pr-sum": { target: 100, tolerance: 0.5 },
    "x-ward-ids": wardIds,
    "x-council": { council_seats: model.council_seats, ward_seats: model.ward_seats, majority: model.majority },
    "x-parties": model.parties.map(p => ({ code: p.code, name: p.name, colour: p.colour })),
    "x-placeholder": Boolean(model.placeholder),
    "x-sources": {
      [srcNames.model]: sha(modelBuf),
      [srcNames.geometry]: sha(geomBuf),
    },
  };
  const geometry = {
    _about: "Generated by worker-api/tools/make_schema.mjs from the source named in _source. Do not edit.",
    _source: { [srcNames.geometry]: sha(geomBuf) },
    W: Number(geom.W), H: Number(geom.H),
    wards: geom.wards.map(w => ({ id: String(w.id), path: w.path })),
  };
  return {
    "generated/forecast.schema.json": JSON.stringify(schema, null, 1) + "\n",
    "generated/geometry.json": JSON.stringify(geometry) + "\n",
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = build(readFileSync(MODEL), readFileSync(GEOM),
    { model: relative(repo, MODEL), geometry: relative(repo, GEOM) });
  let stale = 0;
  for (const [rel, text] of Object.entries(out)) {
    const p = resolve(root, rel);
    if (CHECK) {
      let cur = null;
      try { cur = readFileSync(p, "utf8"); } catch { /* missing counts as stale */ }
      if (cur !== text) { console.error(`STALE: ${rel} differs from a fresh build`); stale++; }
    } else {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (CHECK) {
    if (stale) process.exit(1);
    console.log("generated/* is current");
  }
}
