#!/usr/bin/env node
// The one definition of a reader's entry (a prediction, STYLE.md rule 11),
// entry version FORMAT (interactive/js/make-state.js), and the ward geometry
// the server's share card draws.
//
// `build(model, geometry, names)` returns { schema, geometry }. The SCHEMA is
// built by src/build_make.py from the model artefact it writes from the
// published draws (build_make.model_artefact), and is served inside
// your-forecast/forecast.json: the site Worker validates a sealed entry
// against it (worker-api/src/validate.js), the scorer reads it
// (src/score_forecasts.py) and the page builds against it. There is no second
// copy: the placeholder generated/forecast.schema.json, built from the
// prototype's fixtures, is retired (2026-10-08, guard G13).
//
// Nothing about the council is typed here: the ward list, the roster, the
// council size, the majority and the editor's bounds are read from the
// artefact, and the schema records the sha256 of every source it was built
// from.
//
// The CLI writes only the ward geometry the dormant account store draws:
//   node tools/make_schema.mjs            write generated/geometry.json
//   node tools/make_schema.mjs --check    regenerate it in memory and exit 1 if
//                                         generated/geometry.json differs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { FORMAT } from "../../interactive/js/make-state.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");          // worker-api/
const repo = resolve(root, "..");          // the project

function arg(name, dflt) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : dflt;
}

const sha = buf => createHash("sha256").update(buf).digest("hex");

// The ward geometry the account store's card draws, from the geometry source.
export function geometryOf(geomBuf, geomName) {
  const geom = JSON.parse(geomBuf);
  return {
    _about: "Generated by worker-api/tools/make_schema.mjs from the source named in _source. Do not edit.",
    _source: { [geomName]: sha(geomBuf) },
    W: Number(geom.W), H: Number(geom.H),
    wards: geom.wards.map(w => ({ id: String(w.id), path: w.path })),
  };
}

export function build(modelBuf, geomBuf, srcNames) {
  const model = JSON.parse(modelBuf);
  const geom = JSON.parse(geomBuf);
  const codes = model.parties.map(p => p.code);
  const wardIds = geom.wards.map(w => String(w.id));

  if (wardIds.length !== model.ward_seats)
    throw new Error(`geometry has ${wardIds.length} wards; the model artefact says ward_seats=${model.ward_seats}`);
  if (new Set(codes).size !== codes.length) throw new Error("duplicate party code in roster");
  if (new Set(wardIds).size !== wardIds.length) throw new Error("duplicate ward id in geometry");
  // What src/reader_seats.py and the editor need beyond the roster and the
  // wards. None has a default: a missing one is an artefact that cannot seat
  // or edit an entry.
  for (const k of ["city", "target", "no_pr_list", "editor_bounds"])
    if (!(k in model)) throw new Error(`the model artefact has no ${k}`);
  const stray = model.no_pr_list.filter(c => !codes.includes(c));
  if (stray.length) throw new Error(`no_pr_list names parties not on the roster: ${stray}`);
  const eWards = Object.keys(model.editor_bounds.e || {});
  if (eWards.length !== wardIds.length || !wardIds.every(w => eWards.includes(w)))
    throw new Error("the editor bounds' wards are not the geometry's");

  const code = { type: "string", enum: codes };
  // Whole votes on one ballot, every roster party (BRIEF change 13).
  const ballot = {
    type: "object", additionalProperties: false, required: codes,
    properties: Object.fromEntries(codes.map(c => [c, { type: "integer", minimum: 0 }])),
  };
  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://joburg.whysoserious.city/schema/entry.schema.json",
    title: "A reader's prediction",
    description: "Generated by worker-api/tools/make_schema.mjs. Do not edit. " +
      "Checks JSON Schema cannot express (each ballot holds a vote, a ward winner has a ward vote " +
      "and a list vote, mayor in coalition, coalition members distinct) are in worker-api/src/validate.js, " +
      "which reads this file.",
    type: "object",
    additionalProperties: false,
    required: ["v", "model_ref", "ward_calls", "ward_votes", "list_votes", "coalition"],
    properties: {
      // The entry version: make-state.js FORMAT, the one definition.
      v: { type: "string", const: FORMAT },
      model_ref: { type: "string", enum: [model.model_ref] },
      ward_calls: { type: "array", minItems: wardIds.length, maxItems: wardIds.length, items: code },
      // Each party's whole votes on the ward ballot and on the list ballot.
      // Each ballot's total is the sum of its votes: the prediction states it.
      ward_votes: ballot,
      list_votes: ballot,
      // Who governs: optional, and not scored (an untouched entry names none).
      coalition: { type: "array", minItems: 0, uniqueItems: true, items: code },
      mayor: { oneOf: [{ type: "null" }, code] },
      // The entry's LABEL (owner, 2026-09-29): the reader's own text or X
      // @username, or null for the random default label. Never a real name;
      // never derived from an email.
      display_name: { description: "label shown on the shared prediction; null = the random default label",
        oneOf: [{ type: "null" }, { type: "string", minLength: 1, maxLength: 40 }] },
    },
    "x-ward-ids": wardIds,
    "x-council": { council_seats: model.council_seats, ward_seats: model.ward_seats, majority: model.majority },
    // The `context` argument of src/reader_seats.py's reader_seats(), exactly
    // as it takes it; worker-api/src/seats.js sends it with the entry.
    "x-seat-context": {
      city: String(model.city), target: String(model.target), council: model.council_seats,
      wards: wardIds, parties: codes, no_pr_list: model.no_pr_list.map(String),
    },
    // What the page's editor lets a reader set (src/build_make.py
    // editor_bounds). The editor only: never what an entry may be.
    "x-editor-bounds": model.editor_bounds,
    "x-parties": model.parties.map(p => ({ code: p.code, name: p.name, colour: p.colour })),
    "x-placeholder": Boolean(model.placeholder),
    "x-sources": {
      [srcNames.model]: sha(modelBuf),
      [srcNames.geometry]: sha(geomBuf),
    },
  };
  return { schema, geometry: geometryOf(geomBuf, srcNames.geometry) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const GEOM = resolve(repo, arg("--geometry", "interactive/fixtures/geometry.json"));
  const text = JSON.stringify(geometryOf(readFileSync(GEOM), relative(repo, GEOM))) + "\n";
  const p = resolve(root, "generated/geometry.json");
  if (process.argv.includes("--check")) {
    let cur = null;
    try { cur = readFileSync(p, "utf8"); } catch { /* missing counts as stale */ }
    if (cur !== text) { console.error("STALE: generated/geometry.json differs from a fresh build"); process.exit(1); }
    console.log("generated/geometry.json is current");
  } else {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
    console.log("wrote generated/geometry.json");
  }
}
